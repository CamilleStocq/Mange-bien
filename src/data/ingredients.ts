/** Met à jour les prix restés aux estimations de départ ; un prix modifié à la main est conservé. */
export function refreshDefaultPrices(catalog: Record<string, IngredientInfo>): void {
  const fresh = defaultCatalog();
  for (const [name, old] of PRICES_V1) {
    const k = ingredientKey(name);
    const info = catalog[k];
    if (info && info.price === old && fresh[k]?.price != null) info.price = fresh[k].price;
  }
}

